"""Draws the Vocabulary dock icon (two overlapping flash cards with a swoosh and
a dot) and writes it as a 1-bit icon header in the layout GfxRenderer::drawIcon
reads: bitmap row r / column c land on screen (x = size-1-r, y = c), bit 0 = ink.
Also writes a preview PNG.

Usage: make_vocab_icon.py 32 src/components/icons/vocab.h preview.png  (needs Pillow)"""

import math
import sys

from PIL import Image, ImageDraw

SIZE = int(sys.argv[1]) if len(sys.argv) > 1 else 32
OUT_H = sys.argv[2]
OUT_PNG = sys.argv[3]
SCALE = 8
W = SIZE * SCALE


def card(cx, cy, w, h, angle_deg):
    """Corner points of a rounded card, rotated about its centre (as a polygon)."""
    r = w * 0.16
    pts = []
    for (qx, qy, start) in ((w / 2 - r, -h / 2 + r, -90), (w / 2 - r, h / 2 - r, 0), (-w / 2 + r, h / 2 - r, 90),
                            (-w / 2 + r, -h / 2 + r, 180)):
        for k in range(10):
            a = math.radians(start + k * 9)
            pts.append((qx + r * math.cos(a), qy + r * math.sin(a)))
    t = math.radians(angle_deg)
    return [(cx + x * math.cos(t) - y * math.sin(t), cy + x * math.sin(t) + y * math.cos(t)) for x, y in pts]


# Pixel-grid design: at 32 px a tilt only adds jaggies, so the cards sit
# offset instead, with crisp 2 px strokes (coordinates in icon pixels).
U = SCALE
img = Image.new("L", (W, W), 255)
d = ImageDraw.Draw(img)
def box(x0, y0, x1, y1):
    return [x0 * U, y0 * U, x1 * U - 1, y1 * U - 1]
# Back card (upper left), then the front card (lower right) filled over it.
d.rounded_rectangle(box(2, 2, 20, 26), radius=4 * U, fill=255, outline=0, width=2 * U)
d.rounded_rectangle(box(11, 7, 30, 31), radius=4 * U, fill=255, outline=0, width=2 * U)
# Swoosh rising across the front card toward the dot.
d.arc(box(13, 14, 33, 38), start=200, end=258, fill=0, width=2 * U)
# The dot: a ring with a filled centre.
d.ellipse(box(20, 12, 28, 20), fill=0)
d.ellipse(box(22, 14, 26, 18), fill=255)
d.ellipse(box(23, 15, 25, 17), fill=0)

small = img.resize((SIZE, SIZE), Image.BOX)
bw = small.point(lambda v: 0 if v < 128 else 255, "1")
bw.resize((SIZE * 8, SIZE * 8), Image.NEAREST).save(OUT_PNG)

row_bytes = (SIZE + 7) // 8
data = bytearray(b"\xff" * (row_bytes * SIZE))
px = bw.load()
for r in range(SIZE):
    for c in range(SIZE):
        sx, sy = SIZE - 1 - r, c
        if px[sx, sy] == 0:
            data[r * row_bytes + (c >> 3)] &= ~(0x80 >> (c & 7)) & 0xFF

lines = []
for i in range(0, len(data), 16):
    lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
with open(OUT_H, "w", encoding="utf-8", newline="\n") as f:
    f.write("#pragma once\n#include <cstdint>\n\n")
    f.write("// Vocabulary trainer: two overlapping flash cards with a swoosh and a dot.\n")
    f.write("// Generated by make_vocab_icon.py (1bpp, MSB first, 0 = ink, drawIcon layout).\n")
    f.write(f"static const uint8_t VocabIcon[] = {{\n" + "\n".join(lines) + "\n};\n")
print("ok", SIZE, len(data), "bytes")
