#!/usr/bin/env python3
"""Generate the blue-noise dither matrix in lib/Epub/Epub/converters/BlueNoise.h.

Void-and-cluster (Ulichney 1993) on a 64x64 torus: every threshold rank is
placed where the existing pattern is sparsest, so any gray level dithers into
evenly spread dots with no visible grid. The output is deterministic.

    python scripts/gen_blue_noise.py
"""

import os

import numpy as np

SIZE = 64
SIGMA = 1.5
SEED = 7
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "lib", "Epub", "Epub", "converters",
                   "BlueNoise.h")


def gaussian_kernel():
    d = np.arange(SIZE)
    d = np.minimum(d, SIZE - d)
    g = np.exp(-(d[:, None] ** 2 + d[None, :] ** 2) / (2 * SIGMA * SIGMA))
    return np.fft.rfft2(g)


KERNEL = gaussian_kernel()


def energy(pattern):
    return np.fft.irfft2(np.fft.rfft2(pattern.astype(np.float64)) * KERNEL, s=pattern.shape)


def tightest_cluster(pattern):
    e = np.where(pattern, energy(pattern), -np.inf)
    return np.unravel_index(np.argmax(e), pattern.shape)


def largest_void(pattern):
    e = np.where(pattern, np.inf, energy(pattern))
    return np.unravel_index(np.argmin(e), pattern.shape)


def main():
    n = SIZE * SIZE
    rng = np.random.default_rng(SEED)
    pattern = np.zeros((SIZE, SIZE), dtype=bool)
    pattern.flat[rng.choice(n, n // 10, replace=False)] = True
    # Spread the initial points: move the tightest cluster into the largest void until stable.
    while True:
        c = tightest_cluster(pattern)
        pattern[c] = False
        v = largest_void(pattern)
        if v == c:
            pattern[c] = True
            break
        pattern[v] = True

    rank = np.zeros((SIZE, SIZE), dtype=np.int32)
    ones = int(pattern.sum())
    work = pattern.copy()
    for r in range(ones - 1, -1, -1):
        c = tightest_cluster(work)
        work[c] = False
        rank[c] = r
    work = pattern.copy()
    for r in range(ones, n):
        v = largest_void(work)
        work[v] = True
        rank[v] = r

    values = (rank * 256 // n).astype(np.uint8)
    rows = []
    for y in range(SIZE):
        rows.append("    " + ", ".join(str(int(v)) for v in values[y]) + ",")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("#pragma once\n\n")
        f.write("// Generated by scripts/gen_blue_noise.py; do not edit.\n")
        f.write("// 64x64 void-and-cluster blue-noise thresholds, 0-255, each value used 16 times.\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("inline constexpr int BLUE_NOISE_SIZE = %d;\n" % SIZE)
        f.write("inline constexpr uint8_t BLUE_NOISE[BLUE_NOISE_SIZE * BLUE_NOISE_SIZE] = {\n")
        f.write("\n".join(rows))
        f.write("\n};\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
